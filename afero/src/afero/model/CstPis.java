package afero.model;

public class CstPis {
	
	private int cdCstPis = 0;
	private String dsCstPis = "";
	
	
	public CstPis() {
		
	}


	public CstPis(int cdCstPis, String dsCstPis) {
		
		this.cdCstPis = cdCstPis;
		this.dsCstPis = dsCstPis;
	}


	public int getCdCstPis() {
		return cdCstPis;
	}


	public void setCdCstPis(int cdCstPis) {
		this.cdCstPis = cdCstPis;
	}


	public String getDsCstPis() {
		return dsCstPis;
	}


	public void setDsCstPis(String dsCstPis) {
		this.dsCstPis = dsCstPis;
	}
	
	

}

package afero.model;

public class Csosn {
	
	private int cdCsosn = 0;
	private String dsCsosn = "";
	
	
	public Csosn() {
		
	}


	public Csosn(int cdCsosn, String dsCsosn) {
		
		this.cdCsosn = cdCsosn;
		this.dsCsosn = dsCsosn;
	}


	public int getCdCsosn() {
		return cdCsosn;
	}


	public void setCdCsosn(int cdCsosn) {
		this.cdCsosn = cdCsosn;
	}


	public String getDsCsosn() {
		return dsCsosn;
	}


	public void setDsCsosn(String dsCsosn) {
		this.dsCsosn = dsCsosn;
	}
	
	

}

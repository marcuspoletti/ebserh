package afero.integracao.xprocess;

public class Secao {
	
	String idSecao;
	String nomeSecao;
	
	
	public Secao() {
		
		
	}


	public Secao(String idSecao, String nomeSecao) {
		
		this.idSecao = idSecao;
		this.nomeSecao = nomeSecao;
	}


	public String getIdSecao() {
		return idSecao;
	}


	public void setIdSecao(String idSecao) {
		this.idSecao = idSecao;
	}


	public String getNomeSecao() {
		return nomeSecao;
	}


	public void setNomeSecao(String nomeSecao) {
		this.nomeSecao = nomeSecao;
	}
	
	


}
